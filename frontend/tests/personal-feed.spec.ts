import { expect, test } from '@playwright/test';
import fs from 'node:fs';

test('personal loop consent, watch signals, not interested, undo and reset', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('.listing-panel h2')).toBeVisible();
  await page.getByRole('button', {name:'Sign in', exact:true}).click();
  await page.getByLabel('Phone number').fill(`+35382${String(Date.now()).slice(-7)}`);
  await page.getByRole('button', {name:'Continue with phone'}).click();
  await page.getByLabel('Verification code').fill('123456');
  await page.getByLabel('Your name').fill('Personal loop reviewer');
  await page.getByRole('checkbox', {name:'Personalise my feed using watch time and interactions.'}).check();
  await page.getByRole('button', {name:'Verify & continue'}).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('button', {name:'Your personal loop'})).toBeVisible();
  await page.locator('video').first().scrollIntoViewIfNeeded();
  await expect.poll(() => page.locator('video').first().evaluate(video => (video as HTMLVideoElement).currentTime)).toBeGreaterThan(1);
  const completion = page.waitForRequest(request => request.url().endsWith('/analytics/events') && (request.postDataJSON()?.events || []).some((event: {event_type:string}) => event.event_type === 'completion'));
  await page.getByRole('button', {name:'Next listing'}).click();
  const event = (await completion).postDataJSON().events.find((event: {event_type:string}) => event.event_type === 'completion');
  expect(event.value).toBeGreaterThanOrEqual(0);
  expect(event.value).toBeLessThanOrEqual(1);
  const title = await page.locator('.listing-panel h2').innerText();
  await page.getByRole('button', {name:'Not interested in this listing'}).click();
  await expect(page.getByText('Advert hidden from your loop.')).toBeVisible();
  await expect(page.locator('.listing-panel h2')).not.toHaveText(title);
  await page.getByRole('button', {name:'Undo', exact:true}).click();
  await expect(page.getByText('Advert hidden from your loop.')).toHaveCount(0);
  await page.getByRole('button', {name:'Your personal loop'}).click();
  await expect(page.getByRole('checkbox')).toBeChecked();
  await page.getByRole('button', {name:'Reset learned interests'}).click();
  await expect(page.getByText(/Your learned interests have been reset/)).toBeVisible();
  fs.mkdirSync('../docs/screenshots', {recursive:true});
  await page.screenshot({path:'../docs/screenshots/personal-loop-controls.png'});
  await page.getByRole('checkbox').uncheck();
  await page.getByRole('button', {name:'Save feed preferences'}).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('button', {name:'Tune your loop'})).toBeVisible();
});
