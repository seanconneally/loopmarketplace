import { expect, test } from '@playwright/test';

test('search links, filters, sharing, advert pages and shortlist', async ({ page, context, browser }) => {
  const response = await page.request.get('/api/v1/feed?sort=newest');
  expect(response.status()).toBe(200);
  const listing = (await response.json()).items[0];
  expect(listing).toBeTruthy();
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.goto('/');
  await page.getByRole('searchbox', { name: 'Search cars' }).fill(listing.title);
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page.locator('.listing-panel h2')).toHaveText(listing.title);
  await page.getByLabel('Sort adverts').selectOption('price_asc');
  await page.getByRole('button', { name: /^Filters/ }).click();
  const filters = page.locator('#discovery-filters');
  await filters.getByLabel('Minimum price (€)').fill(String(Math.max(0, listing.price_cents / 100 - 100)));
  await filters.getByLabel('Maximum price (€)').fill(String(listing.price_cents / 100 + 100));
  await filters.getByLabel('Fuel type').selectOption(listing.car.fuel);
  await filters.getByLabel('Transmission', { exact: true }).selectOption(listing.car.transmission);
  await filters.getByLabel('Maximum mileage (km)').fill(String(listing.car.mileage_km));
  await filters.getByRole('button', { name: 'Apply filters' }).click();
  await expect(page.locator('.listing-panel h2')).toHaveText(listing.title);
  const searchUrl = page.url();
  expect(new URL(searchUrl).searchParams.get('fuel')).toBe(listing.car.fuel);
  await page.reload();
  await expect(page.locator('.listing-panel h2')).toHaveText(listing.title);
  await expect(page.getByRole('searchbox', { name: 'Search cars' })).toHaveValue(listing.title);
  await expect(page.getByLabel('Sort adverts')).toHaveValue('price_asc');
  await page.screenshot({ path: '../docs/screenshots/discovery-search.png', fullPage: true });
  await page.getByRole('link', { name: 'Full advert', exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/cars/${listing.id}$`));
  await expect(page.locator('.listing-panel h2')).toHaveText(listing.title);
  await expect(page.locator('.advert-video video')).toBeVisible();
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.getByRole('button', { name: 'Share advert', exact: true }).click();
  await expect(page.getByText('Link copied', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(page.url());
  const sharedUrl = page.url();
  const guestContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const guest = await guestContext.newPage();
  await guest.goto(sharedUrl);
  await expect(guest.locator('.listing-panel h2')).toHaveText(listing.title);
  expect(await guest.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await guest.screenshot({ path: '../docs/screenshots/advert-mobile.png', fullPage: true });
  await page.screenshot({ path: '../docs/screenshots/advert-desktop.png', fullPage: true });
  await guest.goto('/cars/00000000-0000-0000-0000-000000000000');
  await expect(guest.getByRole('heading', { name: 'This advert isn’t available.' })).toBeVisible();
  await guestContext.close();
  await page.getByRole('link', { name: 'Back to discovery', exact: true }).click();
  await expect(page).toHaveURL(searchUrl);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByLabel('Phone number').fill(`+35382${String(Date.now()).slice(-7)}`);
  await page.getByRole('button', { name: /Continue with phone/ }).click();
  await page.getByLabel('Verification code').fill('123456');
  await page.getByLabel('Your name').fill('Discovery buyer');
  await page.getByRole('button', { name: /Verify & continue/ }).click();
  await page.getByRole('button', { name: 'Save this car', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Unsave this car', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Saved cars', exact: true }).first().click();
  const card = page.getByRole('article', { name: listing.title, exact: true });
  await expect(card).toBeVisible();
  await page.screenshot({ path: '../docs/screenshots/shortlist.png', fullPage: true });
  await card.getByRole('link', { name: 'View advert', exact: true }).click();
  await expect(page.locator('.listing-panel h2')).toHaveText(listing.title);
  await page.getByRole('link', { name: 'Back to saved cars', exact: true }).click();
  await card.getByRole('button', { name: `Remove ${listing.title} from saved cars`, exact: true }).click();
  await expect(card).toHaveCount(0);
  await page.getByRole('link', { name: 'Discover', exact: true }).first().click();
  await page.getByRole('searchbox', { name: 'Search cars' }).fill(`no-such-car-${Date.now()}`);
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'No cars match just yet.' })).toBeVisible();
  await page.getByRole('button', { name: 'Reset filters', exact: true }).click();
  await expect(page.getByRole('searchbox', { name: 'Search cars' })).toHaveValue('');
  await expect(page.locator('.listing-panel h2')).toBeVisible();
});
